"""Embeds firefox-ios/WebExtensionsJS/webextension-api.js into a Swift source file."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "firefox-ios", "WebExtensionsJS", "webextension-api.js")
OUTPUT = os.path.join(ROOT, "firefox-ios", "Client", "Frontend", "Browser", "WebExtensions",
                      "WebExtensionAPISource.swift")

HEADER = """// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at http://mozilla.org/MPL/2.0/

// Generated by scripts/flameferret-embed-js.py from firefox-ios/WebExtensionsJS/webextension-api.js.
// Do not edit by hand.

enum WebExtensionAPISource {
    static let source = ###\"\"\"
"""

FOOTER = """
\"\"\"###
}
"""

with open(SOURCE, encoding="utf-8") as handle:
    js = handle.read().rstrip("\n")
if '"""###' in js:
    raise SystemExit("JavaScript contains the raw-string delimiter")
with open(OUTPUT, "w", encoding="utf-8") as handle:
    handle.write(HEADER + js + FOOTER)
print("Wrote", os.path.relpath(OUTPUT, ROOT))
