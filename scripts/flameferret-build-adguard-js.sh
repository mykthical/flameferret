# Rebuilds the AdGuard JavaScript bundles that Flameferret ships as app resources.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/firefox-ios/AdGuardJS"
npm install --no-audit --no-fund
npm run build
python3 - "$ROOT" <<'PY'
import os, sys
root = sys.argv[1]
dist = os.path.join(root, "firefox-ios", "AdGuardJS", "dist")
out = os.path.join(root, "firefox-ios", "Client", "Frontend", "Browser", "AdGuard", "AdGuardJSSource.swift")
parts = []
for name, file in (("content", "adguard-content.js"), ("scriptlets", "adguard-scriptlets.js")):
    js = open(os.path.join(dist, file), encoding="utf-8").read().rstrip("\n")
    if '"####' in js:
        raise SystemExit(file + " contains the raw-string delimiter")
    parts.append(f'    static let {name} = ####"""\n{js}\n"""####\n')
header = (
    "// This Source Code Form is subject to the terms of the Mozilla Public\n"
    "// License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    "// file, You can obtain one at http://mozilla.org/MPL/2.0/\n\n"
    "// swiftlint:disable all\n"
    "// Generated by scripts/flameferret-build-adguard-js.sh from firefox-ios/AdGuardJS.\n"
    "// Bundles AdGuard's @adguard/safari-extension and @adguard/scriptlets (GPL-3.0). Do not edit by hand.\n\n"
    "enum AdGuardJSSource {\n"
)
open(out, "w", encoding="utf-8").write(header + "\n".join(parts) + "}\n")
print("Wrote", out)
PY
